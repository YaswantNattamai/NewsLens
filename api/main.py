@app.get("/events/{event_id}/bias")
def get_bias_predictions(event_id: int):
    """
    Fine-tuned bias classifier predictions, per source, highest-confidence
    "biased" sentences first. Returns an empty list (not an error) if
    BIAS_MODEL_DIR wasn't configured when the event was analyzed — the
    frontend should treat that as "not available for this event," not a
    failure.
    """
    with get_conn() as conn:
        rows = conn.execute(
            """SELECT a.source, p.sentence, p.biased, p.probability
               FROM sentence_bias_predictions p
               JOIN articles a ON a.id = p.article_id
               WHERE a.event_id = %s AND p.biased = TRUE
               ORDER BY p.probability DESC""",
            (event_id,),
        ).fetchall()
    return rows


