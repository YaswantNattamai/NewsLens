@app.on_event("startup")
def on_startup():
    init_schema()


class RegisterEventRequest(BaseModel):
    basil_event_id: str


@app.post("/events")
def register_event(req: RegisterEventRequest):
    """Load a BASIL event's articles into the DB and run the full analysis pipeline on it."""
    try:
        articles = load_event(req.basil_event_id)
    except FileNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e))

    with get_conn() as conn:
        row = conn.execute(
            """INSERT INTO events (topic, source_event_id)
               VALUES (%s, %s)
               ON CONFLICT (source_event_id) DO UPDATE SET topic = EXCLUDED.topic
               RETURNING id""",
            (req.basil_event_id, req.basil_event_id),
        ).fetchone()
        event_id = row["id"]

        conn.execute("DELETE FROM articles WHERE event_id = %s", (event_id,))
        conn.execute("DELETE FROM bias_scores WHERE event_id = %s", (event_id,))

        for art in articles:
            conn.execute(
                """INSERT INTO articles (event_id, source, url, raw_text, clean_text)
                   VALUES (%s, %s, %s, %s, %s)""",
                (event_id, art.source, art.url, art.raw_text, art.raw_text),
            )

    analyze_event(event_id)
    return {"event_id": event_id, "sources": [a.source for a in articles]}


@app.get("/basil-events")
def available_basil_events():
    """List BASIL event ids available on disk, for the EventSearch dropdown."""
    return {"event_ids": list_event_ids()}


@app.get("/events")
def list_loaded_events():
    """Events already loaded + analyzed in this DB — lets the frontend skip re-POSTing on reload."""
    with get_conn() as conn:
        rows = conn.execute(
            "SELECT id, topic, source_event_id, created_at FROM events ORDER BY created_at DESC"
        ).fetchall()
    return rows


@app.get("/events/{event_id}/articles")
def get_articles(event_id: int):
    with get_conn() as conn:
        rows = conn.execute(
            """SELECT a.id, a.source, a.url, a.raw_text, e.topic AS event_topic
               FROM articles a JOIN events e ON e.id = a.event_id
               WHERE a.event_id = %s""", (event_id,)
        ).fetchall()
    if not rows:
        raise HTTPException(status_code=404, detail="No articles for that event id")
    return rows


@app.get("/events/{event_id}/entities")
def get_entities(event_id: int):
    with get_conn() as conn:
        rows = conn.execute(
            """SELECT a.source, m.canonical_entity, m.entity_type,
                      SUM(m.mention_count) AS mention_count
               FROM entity_mentions m
               JOIN articles a ON a.id = m.article_id
               WHERE a.event_id = %s
               GROUP BY a.source, m.canonical_entity, m.entity_type
               ORDER BY m.entity_type, mention_count DESC""",
            (event_id,),
        ).fetchall()
    return rows


